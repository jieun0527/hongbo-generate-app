"""'자료' 폴더의 jpg/png 사진을 인스타그램용 1080x1080 정사각형으로 바꿔 '완성' 폴더에 저장한다.
'로고' 파일이 있으면 오른쪽 아래에 작게 넣는다.
원본 사진은 읽기만 하고 절대 바꾸지 않는다."""

import re
import shutil
from datetime import date, datetime
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageOps

기준폴더 = Path(__file__).resolve().parent
자료폴더 = 기준폴더 / "자료"
완성폴더 = 기준폴더 / "완성"
크기 = 1080
가장자리 = 40


def 로고_찾기():
    """로고 파일을 찾는다. 없으면 None (그러면 로고 넣기는 건너뜀)."""
    for 폴더 in (기준폴더, 자료폴더):
        for 이름 in ("로고.jpg", "로고.jpeg", "로고.png"):
            후보 = 폴더 / 이름
            if 후보.is_file():
                return 후보
    return None


def 로고_넣기(그림, 로고경로):
    """오른쪽 아래에 흰색 둥근 판 + 옅은 그림자 위로 로고를 얹는다."""
    try:
        with Image.open(로고경로) as 원본로고:
            로고 = ImageOps.exif_transpose(원본로고).convert("RGBA")
    except Exception as 오류:
        print(f"로고를 열 수 없어 건너뜀: {오류}")
        return 그림

    # 로고 그림의 투명한 빈 공간을 잘라내고 실제 내용만 남긴다
    내용 = 로고.getchannel("A").point(lambda v: 255 if v > 20 else 0).getbbox()
    if 내용:
        로고 = 로고.crop(내용)

    지름 = round(크기 * 0.15)  # 동그라미 전체가 사진 가로의 15%
    로고폭 = round(지름 * 0.74)  # 원 안쪽에 여유 있게 들어가도록 줄임
    로고높이 = round(로고.height * 로고폭 / 로고.width)
    로고 = 로고.resize((로고폭, 로고높이), Image.LANCZOS)

    x = 크기 - 가장자리 - 지름
    y = 크기 - 가장자리 - 지름

    # 그림자: 검정 원을 흐리게 만들어 살짝 아래에 깐다
    그림자층 = Image.new("RGBA", (크기, 크기), (0, 0, 0, 0))
    ImageDraw.Draw(그림자층).ellipse(
        (x, y + 4, x + 지름, y + 4 + 지름), fill=(0, 0, 0, 35)
    )
    그림자층 = 그림자층.filter(ImageFilter.GaussianBlur(8))

    # 흰 원: 4배 크게 그린 뒤 줄여서 가장자리를 매끄럽게 만든다 (35% 불투명, 많이 투명)
    큰원 = Image.new("L", (지름 * 4, 지름 * 4), 0)
    ImageDraw.Draw(큰원).ellipse((0, 0, 지름 * 4 - 1, 지름 * 4 - 1), fill=90)
    원마스크 = 큰원.resize((지름, 지름), Image.LANCZOS)
    흰원 = Image.new("RGBA", (지름, 지름), (255, 255, 255, 255))
    흰원.putalpha(원마스크)

    결과 = Image.alpha_composite(그림.convert("RGBA"), 그림자층)
    결과.alpha_composite(흰원, (x, y))
    결과.alpha_composite(
        로고, (x + (지름 - 로고폭) // 2, y + (지름 - 로고높이) // 2)
    )
    return 결과.convert("RGB")


def 다음번호(오늘):
    """오늘 이미 만든 파일이 있으면 그 다음 번호부터 시작한다 (덮어쓰기 방지)."""
    번호들 = []
    for 파일 in 완성폴더.glob(f"{오늘}_*.jpg"):
        뒷부분 = 파일.stem.split("_")[-1]
        if 뒷부분.isdigit():
            번호들.append(int(뒷부분))
    return max(번호들, default=0) + 1


