def 정보_읽기(경로):
    """'이름: 값' 줄과 '이번 주 홍보할 것:' 아래 '- ' 목록을 읽는다."""
    글 = 경로.read_text(encoding="utf-8-sig")
    정보 = {"홍보": []}
    홍보중 = False
    for 줄 in 글.splitlines():
        줄 = 줄.strip()
        if not 줄:
            continue
        if 줄.startswith("-") and 홍보중:
            정보["홍보"].append(줄.lstrip("- ").strip())
        elif ":" in 줄:
            이름, 값 = (조각.strip() for 조각 in 줄.split(":", 1))
            홍보중 = 이름.startswith("이번 주 홍보")
            if not 홍보중:
                정보[이름] = 값
    return 정보


def 문장으로(구절):
    """'넣음', '않음' 처럼 끝나는 메모체를 '넣었습니다', '않습니다'로 바꾼다."""
    바꿈표 = (("넣음", "넣었습니다"), ("않음", "않습니다"), ("있음", "있습니다"),
              ("없음", "없습니다"))
    구절 = 구절.strip().rstrip(".")
    앞말 = 구절[: -len("많음")].rstrip() if 구절.endswith("많음") else ""
    if 앞말 and 앞말[-1] not in "이가은는도":
        # '좌석 많음' -> '좌석이 많습니다' (받침이 있으면 이, 없으면 가)
        받침 = (ord(앞말[-1]) - 0xAC00) % 28 != 0 if "가" <= 앞말[-1] <= "힣" else False
        return 앞말 + ("이" if 받침 else "가") + " 많습니다"
    if 구절.endswith("많음"):
        return 구절[: -len("많음")] + "많습니다"
    for 끝, 새끝 in 바꿈표:
        if 구절.endswith(끝):
            return 구절[: -len(끝)] + 새끝
    return 구절


def 홍보거리_나누기(목록):
    """홍보 목록을 신메뉴(작은따옴표 안 이름)와 할인/이벤트로 나눈다."""
    메뉴 = None
    혜택 = []
    기타 = []
    for 항목 in 목록:
        이름 = re.search(r"['‘\"“](.+?)['’\"”]", 항목)
        if 이름 and 메뉴 is None:
            뒤 = 항목[이름.end():].strip()
            가격 = re.search(r"\d[\d,]*\s*원", 뒤)
            설명 = 뒤[가격.end():] if 가격 else 뒤
            설명 = [문장으로(조각) for 조각 in re.split(r"[,，]", 설명) if 조각.strip()]
            메뉴 = {"이름": 이름.group(1), "가격": 가격.group(0).replace(" ", "") if 가격 else "",
                    "설명": 설명}
        elif "할인" in 항목 or "이벤트" in 항목 or "증정" in 항목:
            혜택.append(항목)
        else:
            기타.append(항목)
    return 메뉴, 혜택, 기타


def _받침있나(글자):
    return "가" <= 글자 <= "힣" and (ord(글자) - 0xAC00) % 28 != 0


def 를(단어):
    return "을" if _받침있나(단어[-1]) else "를"


def 혜택_존댓말(혜택문장):
    if 혜택문장.endswith(("할인", "증정")):
        return 혜택문장 + "해 드립니다"
    return 혜택문장 + "입니다"


