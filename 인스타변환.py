def 카톡_만들기(정보):
    """카카오톡 단골 공지용: 3줄, 존댓말."""
    가게 = 정보.get("가게 이름", "우리 가게")
    메뉴, 혜택, 기타 = 홍보거리_나누기(정보["홍보"])
    줄1 = f"안녕하세요, {가게}입니다."
    줄2 = ""
    if 메뉴:
        줄2 = f"이번 주 신메뉴는 '{메뉴['이름']}'" + (f"({메뉴['가격']})" if 메뉴["가격"] else "") + "입니다."
    if 혜택:
        줄2 = (줄2 + " " if 줄2 else "") + 혜택_존댓말(혜택[0]) + "."
    줄3 = "편하게 들러 주세요. 감사합니다."
    return "\n".join(줄 for 줄 in (줄1, 줄2, 줄3) if 줄)


def 해시태그_만들기(정보, 메뉴, 혜택, 개수=10):
    위치 = [조각.replace("지구", "") for 조각 in 정보.get("위치", "").split() if 조각]
    지역 = [조각 for 조각 in 위치 if 조각]
    가게 = 정보.get("가게 이름", "").replace(" ", "")
    특징 = 정보.get("가게 특징", "")
    업종 = ["카페"]
    if "커피" in 가게 or "커피" in 특징:
        업종.append("커피")
    if "스페셜티" in 특징:
        업종.append("스페셜티커피")
    if "로스팅" in 특징:
        업종.append("직접로스팅")

    후보 = []
    if 가게:
        후보.append(가게)
    for 곳 in 지역[:3]:                      # 지역 + 업종 조합
        후보.append(곳 + ("카페" if "카페" not in 곳 else ""))
    후보 += 업종[1:]
    if 메뉴:
        후보.append(메뉴["이름"].replace(" ", ""))
        후보.append("신메뉴")
    for 항목 in 혜택:
        for 단어 in re.findall(r"[가-힣]{3,}", 항목):
            if 단어 in ("아메리카노", "라떼", "에스프레소"):
                후보.append(단어)
    후보 += ["카페추천", "카페스타그램", "오늘의커피", "커피한잔", "일상"]

    결과 = []
    for 태그 in 후보:
        태그 = "#" + 태그
        if 태그 not in 결과:
            결과.append(태그)
    return " ".join(결과[:개수])


def 문구_만들기(정보):
    """인스타그램용 3가지. 사장님 글처럼 '~습니다', 한 줄에 한 문장, 이모지는 1개 이하."""
    가게 = 정보.get("가게 이름", "우리 가게")
    위치 = 정보.get("위치", "")
    특징 = [조각.strip() for 조각 in 정보.get("가게 특징", "").split(",") if 조각.strip()]
    메뉴, 혜택, 기타 = 홍보거리_나누기(정보["홍보"])

    분위기 = 문장으로(특징[1]) if len(특징) > 1 else ""
    혜택문장 = 혜택[0] if 혜택 else ""

    # 1) 감성형: 신메뉴와 자리 이야기를 짧고 담백하게
    감성줄 = ["새 메뉴를 준비했습니다. ☕" if 메뉴 else f"{가게} 소식입니다. ☕"]
    if 메뉴:
        감성줄 += [f"'{메뉴['이름']}'입니다.", ""]
        감성줄 += [설명 + "." for 설명 in 메뉴["설명"]]
    if 분위기:
        감성줄 += ["", 분위기 + ".", "천천히 쉬었다 가세요."]
    감성 = "\n".join(감성줄)

    # 2) 정보형: 필요한 내용만 정리
    정보줄 = [f"[{가게} 이번 주 소식]", ""]
    if 메뉴:
        정보줄.append(f"신메뉴 '{메뉴['이름']}' {메뉴['가격']}".rstrip())
        정보줄 += [f"- {설명}" for 설명 in 메뉴["설명"]]
        정보줄.append("")
    if 혜택문장:
        정보줄 += [혜택문장, ""]
    if 위치:
        정보줄.append(f"위치: {위치}")
    정보형 = "\n".join(정보줄).strip()

    # 3) 이벤트형: 혜택을 먼저 알림
    이벤트줄 = []
    if 혜택문장:
        이벤트줄 += ["이번 주 혜택을 알려드립니다. ☕", "", 혜택_존댓말(혜택문장) + "."]
    if 메뉴:
        이벤트줄.append(f"신메뉴 '{메뉴['이름']}' {메뉴['가격']}입니다.".replace("  ", " "))
    이벤트줄 += ["", 가게] + ([위치] if 위치 else [])
    이벤트 = "\n".join(이벤트줄).strip()

    태그 = 해시태그_만들기(정보, 메뉴, 혜택)
    return [("감성형", 감성), ("정보형", 정보형), ("이벤트형", 이벤트)], 태그


def 문구_저장():
    경로 = 정보파일_찾기()
    if 경로 is None:
        print("'가게 정보.txt' 파일이 없어서 문구 만들기는 건너뛰어요.")
        return
    try:
        정보 = 정보_읽기(경로)
        버전들, 태그 = 문구_만들기(정보)
        블로그제목, 블로그본문, 블로그태그 = 블로그_만들기(정보)
        카톡 = 카톡_만들기(정보)
    except Exception as 오류:
        print(f"문구를 만들지 못했어요 (사진은 이미 저장됐어요): {오류}")
        return

    완성폴더.mkdir(exist_ok=True)
    굵은줄 = "=" * 40
    줄들 = [f"홍보 문구 ({date.today():%Y-%m-%d})", "",
            굵은줄, "[인스타그램용]", 굵은줄, ""]
    for 이름, 글 in 버전들:
        줄들 += [f"■ {이름} ({len(글)}자)", 글, "", 태그, "", "-" * 30, ""]
    줄들 += [굵은줄, f"[네이버 블로그용] (본문 {len(블로그본문)}자)", 굵은줄, "",
             f"제목: {블로그제목}", "", 블로그본문, "", 블로그태그, "",
             굵은줄, "[카카오톡 단골 공지용]", 굵은줄, "", 카톡, ""]
    (완성폴더 / "홍보문구.txt").write_text("\n".join(줄들), encoding="utf-8-sig")
    print("인스타그램·네이버 블로그·카카오톡 문구를 '완성\\홍보문구.txt'에 저장했어요.")


_이번보관함 = None


def 보관함_가져오기():
    """'완성\\이전파일\\오늘날짜_시간' 폴더를 (실행 한 번에 하나만) 만들어 돌려준다."""
    global _이번보관함
    if _이번보관함 is None:
        이름 = datetime.now().strftime("%Y-%m-%d_%H시%M분")
        폴더 = 완성폴더 / "이전파일" / 이름
        번째 = 2
        while 폴더.exists():  # 같은 분에 또 실행하면 덮어쓰지 않고 번호를 붙인다
            폴더 = 완성폴더 / "이전파일" / f"{이름}_{번째}"
            번째 += 1
        폴더.mkdir(parents=True)
        _이번보관함 = 폴더
    return _이번보관함


def 이전파일로_옮기기(파일):
    """지난번 결과 파일은 지우지 않고 날짜·시간 폴더로 옮겨 정리한다."""
    try:
        shutil.move(str(파일), str(보관함_가져오기() / 파일.name))
    except Exception as 오류:
        print(f"  (이전 파일을 정리하지 못했어요: {파일.name}, {오류})")


def 이전결과_정리():
    """'완성' 폴더에 있는 지난번 사진(jpg)을 '완성\\이전파일\\날짜_시간'으로 옮긴다."""
    지난사진 = sorted(p for p in 완성폴더.glob("*.jpg") if p.is_file())
    for 파일 in 지난사진:
        이전파일로_옮기기(파일)
    if 지난사진:
        print(f"지난번 사진 {len(지난사진)}장을 '완성\\이전파일\\{_이번보관함.name}'로 정리했어요.")


def 사진_처리():
    자료폴더.mkdir(exist_ok=True)
    완성폴더.mkdir(exist_ok=True)

    사진들 = sorted(
        p for p in 자료폴더.iterdir()
        if p.is_file() and p.suffix.lower() in (".jpg", ".jpeg", ".png")
        and not p.stem.startswith("로고")  # 로고 파일은 사진이 아니므로 제외
    )
    로고경로 = 로고_찾기()
    if 로고경로 is None:
        print("로고 파일이 없어서 로고 넣기는 건너뛰어요.")
    if not 사진들:
        print("'자료' 폴더에 변환할 사진(jpg, png)이 없어요.")
        print("사진을 '자료' 폴더에 넣고 다시 실행해 주세요.")
        return

    이전결과_정리()  # 새로 만들기 전에 지난번 결과를 날짜·시간 폴더로 옮김
    오늘 = date.today().strftime("%Y%m%d")
    번호 = 다음번호(오늘)
    성공 = 0

    for 사진 in 사진들:
        try:
            with Image.open(사진) as 원본:
                그림 = ImageOps.exif_transpose(원본)  # 누워 있는 사진을 똑바로 세움
                그림 = 그림.convert("RGB")  # png 투명 배경은 jpg에 없으므로 변환
                # 가운데 기준으로 자르고 비율 유지한 채 1080x1080으로 맞춤
                결과 = ImageOps.fit(그림, (크기, 크기), Image.LANCZOS, centering=(0.5, 0.5))
                if 로고경로 is not None:
                    결과 = 로고_넣기(결과, 로고경로)
                저장이름 =f"{오늘}_{번호:02d}.jpg"
                결과.save(완성폴더 / 저장이름, "JPEG", quality=95)
            print(f"완료: {사진.name} -> {저장이름}")
            번호 += 1
            성공 += 1
        except Exception as 오류:
            print(f"건너뜀: {사진.name} (사진을 열 수 없어요: {오류})")

    print(f"\n총 {성공}장을 '완성' 폴더에 저장했어요.")


def main():
    사진_처리()
    문구_저장()


if __name__ == "__main__":
    main()
